# =========================================================
# Skill 1
# 自适应讲解策略
# =========================================================

def adaptive_explanation(
        weak_points=None,
        attempt_count=1
):

    weak_points = weak_points or []


    # =====================================================
    # 第一次学习
    # =====================================================

    if attempt_count <= 1:

        strategy = "conceptual"

        strategy_name = "概念直觉讲解"

        instruction = (
            "这是学生第一次学习当前知识点。"
            "优先使用简单、直观的语言解释核心概念。"
            "先说明它是什么、为什么需要它，"
            "然后使用一个容易理解的简单例子。"
            "不要一开始加入过多复杂公式。"
        )


    # =====================================================
    # 第二次学习
    # =====================================================

    elif attempt_count == 2:

        strategy = "example_based"

        strategy_name = "例子与类比讲解"

        instruction = (
            "学生第一次学习后仍未完全掌握。"
            "不要简单重复上一轮的定义和表达方式。"
            "改用具体数字、实际例子、类比或逐步例题重新解释。"
            "重点解决上一轮暴露出的薄弱点。"
        )


    # =====================================================
    # 第三次学习
    # =====================================================

    else:

        strategy = "step_by_step"

        strategy_name = "分步骤拆解讲解"

        instruction = (
            "学生已经多次学习当前知识点。"
            "不要继续使用与前两轮相同的方式。"
            "把知识点拆成更小的步骤，"
            "一次只处理一个关键概念。"
            "重点检查和解释反复出现的薄弱点。"
        )


    return {

        "skill":
            "adaptive_explanation",

        "strategy":
            strategy,

        "strategy_name":
            strategy_name,

        "instruction":
            instruction,

        "weak_points":
            weak_points,

        "attempt_count":
            attempt_count
    }


# =========================================================
# Skill 2
# 自适应出题策略
# =========================================================

def quiz_generation(
        weak_points=None,
        attempt_count=1
):

    weak_points = weak_points or []


    # =====================================================
    # 第一次学习
    # =====================================================

    if attempt_count <= 1:

        mode = "basic"

        mode_name = "基础理解测试"

        instruction = (
            "生成2道选择题和1道简答题。"
            "题目主要检查学生是否理解当前知识点的核心概念。"
            "选择题不能只测试死记硬背，"
            "简答题应该允许学生使用自己的话解释。"
        )


    # =====================================================
    # 第二次学习
    # =====================================================

    elif attempt_count == 2:

        mode = "targeted"

        mode_name = "薄弱点针对测试"

        instruction = (
            "必须重新生成一套新的2道选择题和1道简答题。"
            "不要重复上一轮题目的问题和选项。"
            "题目重点检查学生上一轮出现的薄弱点。"
            "可以换数字、换场景、换问法，"
            "但仍然围绕当前知识点。"
        )


    # =====================================================
    # 第三次学习
    # =====================================================

    else:

        mode = "diagnostic"

        mode_name = "诊断型测试"

        instruction = (
            "必须重新生成一套不同的2道选择题和1道简答题。"
            "重点判断学生是否真正理解当前核心概念，"
            "以及错误是否可能来自更基础的知识缺口。"
            "不要复制前几轮题目。"
        )


    return {

        "skill":
            "quiz_generation",

        "mode":
            mode,

        "mode_name":
            mode_name,

        "instruction":
            instruction,

        "weak_points":
            weak_points,

        "attempt_count":
            attempt_count
    }


